#!/usr/bin/env python3
"""Calico cat boot sprite (18x15). Prints firmware/acs/cat.h; with --png PATH also renders a check image."""
import sys
W, H = 18, 15
BASE = [  # (x, y, w, h, colour key)
    (1,0,2,1,'K'),(15,0,2,1,'K'),(1,1,1,3,'K'),(3,1,1,1,'K'),(4,2,1,1,'K'),(16,1,1,3,'K'),(14,1,1,1,'K'),(13,2,1,1,'K'),
    (5,3,8,1,'K'),(2,1,1,2,'P'),(3,2,1,2,'P'),(4,3,1,1,'P'),(2,3,1,1,'W'),(15,1,1,2,'P'),(14,2,1,2,'P'),(13,3,1,1,'P'),
    (15,3,1,1,'O'),(0,4,1,9,'K'),(17,4,1,9,'K'),(1,4,16,9,'W'),(9,4,8,1,'O'),(10,5,7,1,'O'),(11,6,6,1,'O'),
    (14,7,3,2,'O'),(15,9,2,3,'O'),(16,12,1,1,'O'),(13,4,2,1,'B'),(14,5,1,1,'B'),(5,4,2,1,'B'),
    (1,13,1,1,'K'),(16,13,1,1,'K'),(2,13,14,1,'W'),(2,14,14,1,'K'),
    (8,9,2,1,'P'),(7,10,1,1,'K'),(10,10,1,1,'K'),(8,11,2,1,'K'),     # nose and "w" mouth
]
STATES = {
    'SLEEP': [(3,8,3,1,'K'),(11,8,3,1,'K')],
    'AWAKE': [(4,7,2,2,'K'),(11,7,2,2,'K'),(4,7,1,1,'W'),(11,7,1,1,'W')],
    'WORK':  [(3,7,3,1,'K'),(11,7,3,1,'K'),(5,8,1,1,'K'),(13,8,1,1,'K')],                  # glancing down at the screen
    'MEOW':  [(3,6,1,1,'K'),(4,7,1,1,'K'),(3,8,1,1,'K'),(14,6,1,1,'K'),(13,7,1,1,'K'),(14,8,1,1,'K'),
              (6,8,6,5,'R'),(6,8,1,1,'W'),(11,8,1,1,'W'),(6,12,1,1,'W'),(11,12,1,1,'W'),(7,11,4,2,'T')],  # > < and a big meow
    'DONE':  [(4,7,1,1,'K'),(3,8,1,1,'K'),(5,8,1,1,'K'),(12,7,1,1,'K'),(11,8,1,1,'K'),(13,8,1,1,'K'),
              (2,10,2,1,'P'),(13,10,2,1,'P')],                                              # ^ ^ with blush
}
def grid(extra):
    g = [['.'] * W for _ in range(H)]
    for x, y, w, h, c in BASE + extra:
        for yy in range(y, y + h):
            for xx in range(x, x + w):
                g[yy][xx] = c
    return [''.join(r) for r in g]
if __name__ == "__main__":
    out = ["// Calico cat boot sprite, 18x15, one char per pixel. Generated by firmware/tools/cat_sprite.py.",
           "// . background  K outline  W white  O orange  B brown  P pink  R mouth  T tongue",
           "#pragma once", "#define CAT_W 18", "#define CAT_H 15"]
    for name, extra in STATES.items():
        out.append(f"static const char CAT_{name}[CAT_H][CAT_W + 1] = {{")
        out += [f'  "{r}",' for r in grid(extra)]
        out.append("};")
    print("\n".join(out))
    if "--png" in sys.argv:
        from PIL import Image
        pal = {'.': (0xF3, 0xEE, 0xE6), 'K': (0x1C,)*3, 'W': (255,)*3, 'O': (0xF0, 0xA0, 0x30), 'B': (0xA0, 0x70, 0x3A), 'P': (0xF2, 0x8C, 0xA0), 'R': (0xE0, 0x30, 0x2A), 'T': (0xF5, 0x9A, 0xAA)}
        im = Image.new('RGB', (len(STATES) * (W + 3), H), pal['.'])
        for i, extra in enumerate(STATES.values()):
            for y, r in enumerate(grid(extra)):
                for x, c in enumerate(r):
                    im.putpixel((i * (W + 3) + x, y), pal[c])
        im.resize((im.width * 12, im.height * 12), Image.NEAREST).save(sys.argv[sys.argv.index("--png") + 1])
